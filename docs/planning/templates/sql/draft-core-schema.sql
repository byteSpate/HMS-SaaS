CREATE EXTENSION IF NOT EXISTS btree_gist;   -- equality operators in exclusion constraints
CREATE EXTENSION IF NOT EXISTS btree_gin;    -- (tenant_id, text) composite GIN indexes
CREATE EXTENSION IF NOT EXISTS pg_trgm;      -- similarity search on names

-- ---------------------------------------------------------------- roles (cluster level; ops-managed)
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'hms_owner')    THEN CREATE ROLE hms_owner NOLOGIN; END IF;
