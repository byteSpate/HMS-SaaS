-- ================================================================= row-level security
-- Every table with a tenant_id column gets ENABLE + FORCE RLS and a fail-closed tenant policy.
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = 'tenant_id' AND NOT a.attisdropped
    WHERE n.nspname = 'hms' AND c.relkind IN ('r','p')
      AND c.relname NOT IN ('membership','user_session')      -- custom policies below / not tenant-owned
  LOOP
    EXECUTE format('ALTER TABLE hms.%I ENABLE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('ALTER TABLE hms.%I FORCE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('CREATE POLICY tenant_isolation ON hms.%I USING (tenant_id = hms.current_tenant_id()) WITH CHECK (tenant_id = hms.current_tenant_id())', r.relname);
  END LOOP;
END $$;

ALTER TABLE tenant ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_self ON tenant USING (id = current_tenant_id()) WITH CHECK (id = current_tenant_id());

-- membership: own tenant, or (at login, before a tenant is chosen) the authenticated user's own rows
ALTER TABLE membership ENABLE ROW LEVEL SECURITY;
ALTER TABLE membership FORCE ROW LEVEL SECURITY;
CREATE POLICY membership_tenant ON membership
  USING (tenant_id = current_tenant_id() OR user_id = current_app_user_id())
  WITH CHECK (tenant_id = current_tenant_id());

RESET ROLE;

