-- ---------------------------------------------------------------- tenant context helpers
CREATE FUNCTION current_tenant_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid $$;
CREATE FUNCTION current_app_user_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT NULLIF(current_setting('app.user_id', true), '')::uuid $$;

-- ================================================================= identity & access
CREATE TABLE tenant (
  id            uuid PRIMARY KEY DEFAULT uuidv7(),
  code          text NOT NULL UNIQUE,
  name_en       text,
  name_bn       text,
  status        text NOT NULL DEFAULT 'PROVISIONED'
                CHECK (status IN ('PROVISIONING','PROVISIONED','ACTIVE','SUSPENDED','TERMINATED')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  version       integer NOT NULL DEFAULT 1,
  CHECK (name_en IS NOT NULL OR name_bn IS NOT NULL)
);

CREATE TABLE facility (
  tenant_id     uuid NOT NULL REFERENCES tenant(id),
  id            uuid NOT NULL DEFAULT uuidv7(),
  code          text NOT NULL,
  name_en       text,
  name_bn       text,
  timezone      text NOT NULL DEFAULT 'Asia/Dhaka',
  version       integer NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, code)
);

CREATE TABLE department (
  tenant_id     uuid NOT NULL,
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  facility_id   uuid NOT NULL,
  code          text NOT NULL,
  name_en       text,
  name_bn       text,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, facility_id, code),
  FOREIGN KEY (tenant_id, facility_id) REFERENCES facility (tenant_id, id)
);

-- Global login identity (a person may hold memberships in several tenants).
CREATE TABLE user_account (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  username        text NOT NULL,
  display_name    text NOT NULL,
  password_hash   text NOT NULL,                 -- argon2id encoded string
  totp_secret_enc bytea,                         -- encrypted at application level
  status          text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','LOCKED_TEMPORARY','LOCKED_ADMIN','DISABLED')),
  failed_attempts integer NOT NULL DEFAULT 0,
  locked_until    timestamptz,
  lock_reason     text,
  preferred_lang  text NOT NULL DEFAULT 'bn-BD' CHECK (preferred_lang IN ('bn-BD','en')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  version         integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX user_account_username_uq ON user_account (lower(username));

CREATE TABLE membership (
  tenant_id     uuid NOT NULL REFERENCES tenant(id),
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  user_id       uuid NOT NULL REFERENCES user_account(id),
  status        text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('INVITED','ACTIVE','SUSPENDED','REVOKED')),
  facility_ids  uuid[] NOT NULL DEFAULT '{}',    -- scope; empty = all facilities of tenant (one today)
  roles_version integer NOT NULL DEFAULT 1,      -- bumped on role change → permission cache key
  created_at    timestamptz NOT NULL DEFAULT now(),
  version       integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, user_id)
);

CREATE TABLE role (
  tenant_id     uuid NOT NULL REFERENCES tenant(id),
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  code          text NOT NULL,
  name_en       text NOT NULL,
  name_bn       text,
  privileged    boolean NOT NULL DEFAULT false,  -- requires MFA (CP-12)
  version       integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, code)
);

CREATE TABLE role_permission (
  tenant_id       uuid NOT NULL,
  role_id         uuid NOT NULL,
  permission_code text NOT NULL CHECK (permission_code ~ '^[a-z_]+(\.[a-z_]+)+$'),
  PRIMARY KEY (tenant_id, role_id, permission_code),
  FOREIGN KEY (tenant_id, role_id) REFERENCES role (tenant_id, id)
);

CREATE TABLE membership_role (
  tenant_id     uuid NOT NULL,
  membership_id uuid NOT NULL,
  role_id       uuid NOT NULL,
  PRIMARY KEY (tenant_id, membership_id, role_id),
  FOREIGN KEY (tenant_id, membership_id) REFERENCES membership (tenant_id, id),
  FOREIGN KEY (tenant_id, role_id)       REFERENCES role (tenant_id, id)
);

-- Server-side sessions (looked up by hashed token; not tenant-scoped until a membership is chosen).
CREATE TABLE user_session (
  id_hash              bytea PRIMARY KEY,
  user_id              uuid NOT NULL REFERENCES user_account(id),
  tenant_id            uuid REFERENCES tenant(id),
  membership_id        uuid,
  csrf_token_hash      bytea NOT NULL,
  mfa_verified         boolean NOT NULL DEFAULT false,
  created_at           timestamptz NOT NULL DEFAULT now(),
  last_seen_at         timestamptz NOT NULL DEFAULT now(),
  idle_expires_at      timestamptz NOT NULL,
  absolute_expires_at  timestamptz NOT NULL,
  revoked_at           timestamptz,
  FOREIGN KEY (tenant_id, membership_id) REFERENCES membership (tenant_id, id)
);

-- Tenant-scoped business number sequences (MRN, invoice, receipt, specimen …). Format = CP-09 (OPEN).
CREATE TABLE number_sequence (
  tenant_id     uuid NOT NULL REFERENCES tenant(id),
  sequence_key  text NOT NULL,                  -- e.g. 'MRN', 'INV-SERVICE-2026', 'RCPT-2026'
  next_value    bigint NOT NULL DEFAULT 1 CHECK (next_value > 0),
  PRIMARY KEY (tenant_id, sequence_key)
);

-- ================================================================= patients & scheduling
CREATE TABLE patient (
  tenant_id             uuid NOT NULL REFERENCES tenant(id),
  id                    uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  mrn                   text NOT NULL,
  identity_status       text NOT NULL DEFAULT 'CONFIRMED' CHECK (identity_status IN ('CONFIRMED','TEMPORARY')),
  name_bn               text,
  name_en               text,
  sex                   text NOT NULL CHECK (sex IN ('MALE','FEMALE','OTHER','UNKNOWN')),
  birth_date            date,
  birth_date_precision  text NOT NULL DEFAULT 'UNKNOWN' CHECK (birth_date_precision IN ('EXACT','YEAR_ESTIMATED','UNKNOWN')),
  reported_age_years    smallint CHECK (reported_age_years BETWEEN 0 AND 150),
  reported_age_on       date,
  phone_raw             text,
  phone_normalized      text,
  address_text          text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  created_by            uuid NOT NULL,
  version               integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, mrn),
  CHECK (identity_status = 'TEMPORARY' OR name_bn IS NOT NULL OR name_en IS NOT NULL),
  CHECK (reported_age_years IS NULL OR reported_age_on IS NOT NULL)
);
CREATE INDEX patient_phone_idx   ON patient (tenant_id, phone_normalized) WHERE phone_normalized IS NOT NULL;
CREATE INDEX patient_name_en_trgm ON patient USING gin (tenant_id, name_en gin_trgm_ops);
CREATE INDEX patient_name_bn_trgm ON patient USING gin (tenant_id, name_bn gin_trgm_ops);

CREATE TABLE patient_identifier (
  tenant_id     uuid NOT NULL,
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  patient_id    uuid NOT NULL,
  kind          text NOT NULL CHECK (kind IN ('NID','BIRTH_REGISTRATION','PASSPORT','OTHER')),
  value         text NOT NULL,              -- consider application-level encryption (E §5)
  value_last4   text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, patient_id) REFERENCES patient (tenant_id, id)
);
CREATE INDEX patient_identifier_lookup ON patient_identifier (tenant_id, kind, value);  -- not unique: duplicate signal only

CREATE TABLE patient_identity_history (     -- append-only
  tenant_id     uuid NOT NULL,
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  patient_id    uuid NOT NULL,
  changed_at    timestamptz NOT NULL DEFAULT now(),
  changed_by    uuid NOT NULL,
  reason        text NOT NULL,
  previous      jsonb NOT NULL,
  FOREIGN KEY (tenant_id, patient_id) REFERENCES patient (tenant_id, id)
);

CREATE TABLE practitioner (
  tenant_id       uuid NOT NULL REFERENCES tenant(id),
  id              uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  name_en         text,
  name_bn         text,
  degrees         text,
  specialty       text,
  department_id   uuid,
  registration_no text,
  user_id         uuid REFERENCES user_account(id),
  active          boolean NOT NULL DEFAULT true,
  version         integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, department_id) REFERENCES department (tenant_id, id),
  CHECK (name_en IS NOT NULL OR name_bn IS NOT NULL)
);

CREATE TABLE schedule_session (
  tenant_id       uuid NOT NULL,
  id              uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  practitioner_id uuid NOT NULL,
  facility_id     uuid NOT NULL,
  session_date    date NOT NULL,              -- business date in facility timezone
  starts_at       timestamptz NOT NULL,
  ends_at         timestamptz NOT NULL,
  capacity        integer NOT NULL CHECK (capacity > 0),
  booked_count    integer NOT NULL DEFAULT 0,
  status          text NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('DRAFT','PUBLISHED','CANCELLED')),
  version         integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  CHECK (ends_at > starts_at),
  CONSTRAINT schedule_session_capacity CHECK (booked_count BETWEEN 0 AND capacity),  -- → CAPACITY_FULL (CP-11 interim)
  FOREIGN KEY (tenant_id, practitioner_id) REFERENCES practitioner (tenant_id, id),
  FOREIGN KEY (tenant_id, facility_id)     REFERENCES facility (tenant_id, id)
);

CREATE TABLE appointment (
  tenant_id             uuid NOT NULL,
  id                    uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  patient_id            uuid NOT NULL,
  schedule_session_id   uuid NOT NULL,
  status                text NOT NULL DEFAULT 'BOOKED' CHECK (status IN ('BOOKED','CHECKED_IN','RESCHEDULED','CANCELLED','NO_SHOW')),
  rescheduled_from_id   uuid,
  follow_up_of_visit_id uuid,
  booked_at             timestamptz NOT NULL DEFAULT now(),
  booked_by             uuid NOT NULL,
  cancel_reason         text,
  version               integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, patient_id)          REFERENCES patient (tenant_id, id),
  FOREIGN KEY (tenant_id, schedule_session_id) REFERENCES schedule_session (tenant_id, id),
  FOREIGN KEY (tenant_id, rescheduled_from_id) REFERENCES appointment (tenant_id, id)
);
CREATE INDEX appointment_session_idx ON appointment (tenant_id, schedule_session_id, status);

CREATE TABLE visit (
  tenant_id                 uuid NOT NULL,
  id                        uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  facility_id               uuid NOT NULL,
  department_id             uuid,
  patient_id                uuid NOT NULL,
  kind                      text NOT NULL CHECK (kind IN ('OPD_CONSULTATION','DIAGNOSTIC','EMERGENCY')),
  status                    text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','COMPLETED','CANCELLED')),
  attending_practitioner_id uuid,
  appointment_id            uuid,
  source_visit_id           uuid,
  queue_number              integer,
  arrived_at                timestamptz NOT NULL DEFAULT now(),
  created_by                uuid NOT NULL,
  version                   integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, appointment_id),               -- one visit per appointment (FR-VIS-002); NULLs allowed
  CHECK (kind <> 'OPD_CONSULTATION' OR attending_practitioner_id IS NOT NULL),
  FOREIGN KEY (tenant_id, facility_id)               REFERENCES facility (tenant_id, id),
  FOREIGN KEY (tenant_id, patient_id)                REFERENCES patient (tenant_id, id),
  FOREIGN KEY (tenant_id, attending_practitioner_id) REFERENCES practitioner (tenant_id, id),
  FOREIGN KEY (tenant_id, appointment_id)            REFERENCES appointment (tenant_id, id),
  FOREIGN KEY (tenant_id, source_visit_id)           REFERENCES visit (tenant_id, id)
);
CREATE INDEX visit_patient_idx  ON visit (tenant_id, patient_id, arrived_at DESC);
CREATE INDEX visit_worklist_idx ON visit (tenant_id, attending_practitioner_id, status, arrived_at) WHERE status = 'OPEN';

-- ================================================================= catalogue, prices, orders
CREATE TABLE service_item (
  tenant_id             uuid NOT NULL REFERENCES tenant(id),
  id                    uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  code                  text NOT NULL,
  name_en               text,
  name_bn               text,
  category              text NOT NULL CHECK (category IN ('CONSULTATION','LAB','IMAGING','PROCEDURE','MEDICINE','BED','OTHER')),
  billable              boolean NOT NULL DEFAULT true,
  active                boolean NOT NULL DEFAULT true,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, code)
);

CREATE TABLE policy_version (               -- generic effective-dated configuration (CP-*)
  tenant_id       uuid NOT NULL REFERENCES tenant(id),
  id              uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  policy_key      text NOT NULL,              -- e.g. 'payment_eligibility', 'direct_orderable_tests'
  version_no      integer NOT NULL,
  effective_from  timestamptz NOT NULL,
  body            jsonb NOT NULL,             -- validated by Zod schema per policy_key
  status          text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','RETIRED')),
  published_by    uuid,
  published_at    timestamptz,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, policy_key, version_no)
);

CREATE TABLE price_list_version (
  tenant_id       uuid NOT NULL REFERENCES tenant(id),
  id              uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  version_no      integer NOT NULL,
  effective_from  timestamptz NOT NULL,
  status          text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','RETIRED')),
  published_by    uuid,
  published_at    timestamptz,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, version_no)
);

CREATE TABLE price_list_item (
  tenant_id               uuid NOT NULL,
  id                      uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  price_list_version_id   uuid NOT NULL,
  service_item_id         uuid NOT NULL,
  practitioner_id         uuid,                 -- doctor-fee rows are per practitioner (Q-038 rules OPEN)
  unit_price              numeric(18,2) NOT NULL CHECK (unit_price >= 0),
  UNIQUE NULLS NOT DISTINCT (tenant_id, price_list_version_id, service_item_id, practitioner_id),
  FOREIGN KEY (tenant_id, price_list_version_id) REFERENCES price_list_version (tenant_id, id),
  FOREIGN KEY (tenant_id, service_item_id)       REFERENCES service_item (tenant_id, id),
  FOREIGN KEY (tenant_id, practitioner_id)       REFERENCES practitioner (tenant_id, id)
);

CREATE TABLE service_order (
  tenant_id                   uuid NOT NULL,
  id                          uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  patient_id                  uuid NOT NULL,
  visit_id                    uuid,
  admission_id                uuid,
  service_item_id             uuid NOT NULL,
  source                      text NOT NULL CHECK (source IN ('CONSULTATION','RECEPTION_DIRECT','WARD','EMERGENCY')),
  requested_by                uuid NOT NULL,     -- authenticated user (never client-supplied)
  requesting_practitioner_id  uuid,
  priority                    text NOT NULL DEFAULT 'ROUTINE' CHECK (priority IN ('ROUTINE','URGENT')),
  status                      text NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','IN_PROGRESS','COMPLETED','CANCELLED')),
  direct_order_policy_version_id uuid,
  cancel_reason               text,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  version                     integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  CHECK (visit_id IS NOT NULL OR admission_id IS NOT NULL),
  CHECK (status <> 'CANCELLED' OR cancel_reason IS NOT NULL),
  FOREIGN KEY (tenant_id, patient_id)      REFERENCES patient (tenant_id, id),
  FOREIGN KEY (tenant_id, visit_id)        REFERENCES visit (tenant_id, id),
  FOREIGN KEY (tenant_id, service_item_id) REFERENCES service_item (tenant_id, id)
  -- admission FK added after admission table (below)
);

-- ================================================================= billing
CREATE TABLE cashier_session (
  tenant_id       uuid NOT NULL,
  id              uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  facility_id     uuid NOT NULL,
  cashier_user_id uuid NOT NULL,
  status          text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED_PENDING_REVIEW','REVIEWED')),
  opened_at       timestamptz NOT NULL DEFAULT now(),
  closed_at       timestamptz,
  counted         jsonb,                          -- {"CASH":"1500.00", ...}
  reviewed_by     uuid,
  reviewed_at     timestamptz,
  review_note     text,
  version         integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  CHECK (reviewed_by IS NULL OR reviewed_by <> cashier_user_id),   -- segregation (UC-BIL-04 D2)
  FOREIGN KEY (tenant_id, facility_id) REFERENCES facility (tenant_id, id)
);
CREATE UNIQUE INDEX cashier_one_open_session ON cashier_session (tenant_id, cashier_user_id) WHERE status = 'OPEN';

CREATE TABLE invoice (
  tenant_id     uuid NOT NULL,
  id            uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  number        text NOT NULL,
  type          text NOT NULL CHECK (type IN ('DOCTOR_FEE','SERVICE','IPD_RUNNING','PHARMACY')),
  patient_id    uuid NOT NULL,
  visit_id      uuid,
  admission_id  uuid,
  currency      char(3) NOT NULL DEFAULT 'BDT',
  status        text NOT NULL DEFAULT 'ISSUED'
                CHECK (status IN ('ISSUED','PARTIALLY_PAID','PAID','CANCELLED','OPEN','FINAL_ISSUED','SETTLED')),
  total         numeric(18,2) NOT NULL DEFAULT 0,
  paid          numeric(18,2) NOT NULL DEFAULT 0,
  issued_at     timestamptz NOT NULL DEFAULT now(),
  version       integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, number),
  CHECK (total >= 0 AND paid >= 0 AND paid <= total),
  CHECK ((type IN ('DOCTOR_FEE','SERVICE') AND visit_id IS NOT NULL)
      OR (type = 'IPD_RUNNING' AND admission_id IS NOT NULL)
      OR (type = 'PHARMACY')),
  FOREIGN KEY (tenant_id, patient_id) REFERENCES patient (tenant_id, id),
  FOREIGN KEY (tenant_id, visit_id)   REFERENCES visit (tenant_id, id)
);
-- C-008: one combined SERVICE invoice and one DOCTOR_FEE invoice per OPD visit
CREATE UNIQUE INDEX invoice_one_service_per_visit ON invoice (tenant_id, visit_id) WHERE type = 'SERVICE';
CREATE UNIQUE INDEX invoice_one_docfee_per_visit  ON invoice (tenant_id, visit_id) WHERE type = 'DOCTOR_FEE';
CREATE UNIQUE INDEX invoice_one_running_per_adm   ON invoice (tenant_id, admission_id) WHERE type = 'IPD_RUNNING';

CREATE TABLE charge (                          -- append-only (ADR-009)
  tenant_id               uuid NOT NULL,
  id                      uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  patient_id              uuid NOT NULL,
  service_item_id         uuid NOT NULL,
  source_module           text NOT NULL,
  source_type             text NOT NULL,
  source_id               text NOT NULL,
  source_event            text NOT NULL,
  quantity                numeric(14,3) NOT NULL CHECK (quantity > 0),
  unit_price              numeric(18,2) NOT NULL CHECK (unit_price >= 0),
  amount                  numeric(18,2) NOT NULL CHECK (amount >= 0),
  price_list_version_id   uuid NOT NULL,
  service_time            timestamptz NOT NULL,
  posted_at               timestamptz NOT NULL DEFAULT now(),
  posted_by               uuid NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, source_module, source_type, source_id, source_event),   -- FPR-09
  FOREIGN KEY (tenant_id, patient_id)            REFERENCES patient (tenant_id, id),
  FOREIGN KEY (tenant_id, service_item_id)       REFERENCES service_item (tenant_id, id),
  FOREIGN KEY (tenant_id, price_list_version_id) REFERENCES price_list_version (tenant_id, id)
);

CREATE TABLE invoice_line (
  tenant_id         uuid NOT NULL,
  id                uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  invoice_id        uuid NOT NULL,
  charge_id         uuid NOT NULL,
  line_no           integer NOT NULL,
  category          text NOT NULL CHECK (category IN ('MEDICINE','NON_MEDICINE')),   -- SRC-B03 subtotals
  description_en    text,
  description_bn    text,
  net_amount        numeric(18,2) NOT NULL CHECK (net_amount >= 0),
  allocated_amount  numeric(18,2) NOT NULL DEFAULT 0,
  status            text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','CANCELLED','REVERSED')),
  eligibility       text NOT NULL DEFAULT 'NOT_ELIGIBLE' CHECK (eligibility IN ('ELIGIBLE','NOT_ELIGIBLE')),
  eligibility_policy_version_id uuid,
  version           integer NOT NULL DEFAULT 1,
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, charge_id),
  UNIQUE (tenant_id, invoice_id, line_no),
  CONSTRAINT invoice_line_allocation_within_net CHECK (allocated_amount >= 0 AND allocated_amount <= net_amount),  -- → AMOUNT_EXCEEDS_BALANCE
  CHECK (status <> 'CANCELLED' OR allocated_amount = 0),             -- interim cancel rule (FR-BIL-020)
  FOREIGN KEY (tenant_id, invoice_id) REFERENCES invoice (tenant_id, id),
  FOREIGN KEY (tenant_id, charge_id)  REFERENCES charge (tenant_id, id)
);

CREATE TABLE payment (                         -- append-only
  tenant_id           uuid NOT NULL,
  id                  uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  invoice_id          uuid NOT NULL,
  cashier_session_id  uuid NOT NULL,
  method              text NOT NULL CHECK (method IN ('CASH','CARD','MOBILE','BANK_TRANSFER')),
  provider_label      text,
  external_reference  text,
  amount              numeric(18,2) NOT NULL CHECK (amount > 0),
  currency            char(3) NOT NULL DEFAULT 'BDT',
  receipt_number      text NOT NULL,
  received_at         timestamptz NOT NULL DEFAULT now(),
  recorded_by         uuid NOT NULL,
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, receipt_number),
  FOREIGN KEY (tenant_id, invoice_id)         REFERENCES invoice (tenant_id, id),
  FOREIGN KEY (tenant_id, cashier_session_id) REFERENCES cashier_session (tenant_id, id)
);
CREATE INDEX payment_session_idx ON payment (tenant_id, cashier_session_id, method);
CREATE INDEX payment_day_idx     ON payment (tenant_id, received_at);

CREATE TABLE payment_allocation (              -- append-only
  tenant_id         uuid NOT NULL,
  id                uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  payment_id        uuid NOT NULL,
  invoice_id        uuid NOT NULL,
  invoice_line_id   uuid,                       -- NULL only for IPD running-account allocation (ADR-016)
  amount            numeric(18,2) NOT NULL CHECK (amount > 0),
  created_at        timestamptz NOT NULL DEFAULT now(),
