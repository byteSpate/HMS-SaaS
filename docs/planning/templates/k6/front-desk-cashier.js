import http from 'k6/http';
import { check, group, sleep } from 'k6';
import { SharedArray } from 'k6/data';

const BASE = __ENV.BASE_URL || 'https://staging.example.invalid';

// Synthetic users/patients generated by packages/testkit volume seed and exported to JSON.
const receptionists = new SharedArray('rcp', () => JSON.parse(open('./data/receptionists.json')));
const cashiers      = new SharedArray('csh', () => JSON.parse(open('./data/cashiers.json')));
const searchTerms   = new SharedArray('q',   () => JSON.parse(open('./data/search-terms.json')));   // phones, MRNs, Bangla names

export const options = {
  scenarios: {
    reception: {
      executor: 'ramping-arrival-rate', exec: 'reception',
      startRate: 1, timeUnit: '1s', preAllocatedVUs: 20, maxVUs: 60,
      stages: [ { target: 2, duration: '10m' }, { target: 2, duration: '30m' } ],   // ≈ pilot peak (M §4); scale for 2×
    },
    cashier: {
      executor: 'ramping-arrival-rate', exec: 'cashier',
      startRate: 1, timeUnit: '1s', preAllocatedVUs: 20, maxVUs: 60,
      stages: [ { target: 1, duration: '10m' }, { target: 1, duration: '30m' } ],
    },
  },
  thresholds: {                                    // PROPOSED targets (C15 NFR-PERF-001, M §7)
    'http_req_failed': ['rate<0.005'],
    'http_req_duration{kind:read}': ['p(95)<500'],
    'http_req_duration{kind:command}': ['p(95)<800', 'p(99)<2000'],
  },
};

function login(user) {
  const res = http.post(`${BASE}/api/v1/auth/login`, JSON.stringify({ username: user.username, password: user.password }),
    { headers: { 'Content-Type': 'application/json' }, tags: { kind: 'command' } });
  check(res, { 'login 200': (r) => r.status === 200 });
  return res.json('csrfToken');                    // cookie jar keeps the session cookie per VU
}

function uuid() {                                  // idempotency key per user intent
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0; return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

export function reception() {
  const u = receptionists[__VU % receptionists.length];
  const csrf = login(u);
  group('search → open → check-in', () => {
    const q = searchTerms[Math.floor(Math.random() * searchTerms.length)];
    const s = http.get(`${BASE}/api/v1/patients/search?q=${encodeURIComponent(q)}&limit=20`, { tags: { kind: 'read' } });
    check(s, { 'search 200': (r) => r.status === 200 });
    sleep(2);
    const appt = s.json('items.0.todayAppointmentId');
    if (appt) {
      const r = http.post(`${BASE}/api/v1/scheduling/appointments/${appt}:check-in`, '{}', {
        headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf, 'Idempotency-Key': uuid(), 'If-Match': s.json('items.0.todayAppointmentEtag') },
        tags: { kind: 'command' },
      });
      check(r, { 'check-in 201/409': (x) => x.status === 201 || x.status === 409 });   // 409 = already checked in by another VU
    }
  });
  sleep(3);
}

export function cashier() {
  const u = cashiers[__VU % cashiers.length];
  const csrf = login(u);
  group('open visit → pay doctor fee', () => {
    const q = http.get(`${BASE}/api/v1/billing/cashier-queue?limit=20`, { tags: { kind: 'read' } });
    check(q, { 'queue 200': (r) => r.status === 200 });
    const inv = q.json('items.0');
    if (!inv) return;
    const body = JSON.stringify({
      method: 'CASH',
      amount: { amount: inv.balance.amount, currency: 'BDT' },
      allocations: inv.unpaidLines.map((l) => ({ invoiceLineId: l.id, amount: l.remaining })),
    });
    const r = http.post(`${BASE}/api/v1/billing/invoices/${inv.id}/payments`, body, {
      headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf, 'Idempotency-Key': uuid(), 'If-Match': inv.etag },
      tags: { kind: 'command' },
    });
    check(r, { 'payment 201 or expected conflict': (x) => [201, 409].includes(x.status) });
  });
  sleep(4);
}
